CREATE TABLE BIKES (
  BIKE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME VARCHAR2(200) NOT NULL,
  BRAND VARCHAR2(100),
  PRICE NUMBER(12,2),
  MAX_POWER NUMBER(10,2),
  MAX_TORQUE NUMBER(10,2),
  COOLING_SYSTEM VARCHAR2(100),
  TRANSMISSION VARCHAR2(100),
  TRANSMISSION_TYPE VARCHAR2(100),
  DISPLACEMENT NUMBER(8,2),
  CYLINDERS NUMBER(4),
  BORE NUMBER(8,2),
  STROKE NUMBER(8,2),
  VALVES_PER_CYLINDER NUMBER(4),
  SPARK_PLUGS VARCHAR2(100),
  GEAR_SHIFTING_PATTERN VARCHAR2(100),
  CLUTCH VARCHAR2(100),
  FUEL_TANK_CAPACITY NUMBER(8,2),
  MILEAGE_ARAI NUMBER(8,2),
  MILEAGE_OWNER_REPORTED NUMBER(8,2),
  TOP_SPEED NUMBER(8,2),
  BRAKING_SYSTEM VARCHAR2(100),
  FRONT_BRAKE_TYPE VARCHAR2(100),
  FRONT_BRAKE_SIZE NUMBER(8,2),
  REAR_TYRE_SIZE VARCHAR2(100),
  TYRE_TYPE VARCHAR2(100),
  RADIAL_TYRES VARCHAR2(30),
  REAR_BRAKE_TYPE VARCHAR2(100),
  REAR_BRAKE_SIZE NUMBER(8,2),
  WHEEL_TYPE VARCHAR2(100),
  FRONT_WHEEL_SIZE NUMBER(8,2),
  REAR_WHEEL_SIZE NUMBER(8,2),
  FRONT_TYRE_SIZE VARCHAR2(100),
  FRONT_TYRE_PRESSURE_RIDER NUMBER(8,2),
  REAR_TYRE_PRESSURE_RIDER NUMBER(8,2),
  FRONT_TYRE_PRESSURE_RIDER_PILLION NUMBER(8,2),
  REAR_TYRE_PRESSURE_RIDER_PILLION NUMBER(8,2),
  KERB_WEIGHT NUMBER(8,2),
  OVERALL_LENGTH NUMBER(8,2),
  OVERALL_WIDTH NUMBER(8,2),
  WHEELBASE NUMBER(8,2),
  GROUND_CLEARANCE NUMBER(8,2),
  SEAT_HEIGHT NUMBER(8,2),
  OVERALL_HEIGHT NUMBER(8,2),
  CHASSIS_TYPE VARCHAR2(200),
  IMAGES_URL VARCHAR2(2000),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_BIKES_BRAND ON BIKES (BRAND);
CREATE INDEX IDX_BIKES_PRICE ON BIKES (PRICE);
CREATE INDEX IDX_BIKES_DISPLACEMENT ON BIKES (DISPLACEMENT);

CREATE TABLE BOOKINGS (
  BOOKING_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  BIKE_ID NUMBER NOT NULL,
  CUSTOMER_NAME VARCHAR2(150) NOT NULL,
  CUSTOMER_EMAIL VARCHAR2(254) NOT NULL,
  CUSTOMER_PHONE VARCHAR2(30) NOT NULL,
  CUSTOMER_CITY VARCHAR2(100),
  NOTES VARCHAR2(1000),
  BOOKING_STATUS VARCHAR2(30) DEFAULT 'DEMO_REQUESTED' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_BOOKINGS_BIKE FOREIGN KEY (BIKE_ID) REFERENCES BIKES(BIKE_ID)
);

CREATE INDEX IDX_BOOKINGS_BIKE ON BOOKINGS (BIKE_ID);
CREATE INDEX IDX_BOOKINGS_CREATED ON BOOKINGS (CREATED_AT);
